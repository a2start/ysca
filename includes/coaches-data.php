function getCoachById(string $id): ?array
{
    $list = getCoachesList();
    $id = strtolower(trim($id));
    if (isset($list[$id])) {
        return $list[$id];
    }
    
    foreach ($list as $coach) {
        if ($coach['id'] === $id || $coach['slug'] === $id || strtolower($coach['name']) === $id) {
            return $coach;
        }
    }
    return null;
}
